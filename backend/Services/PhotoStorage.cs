using Microsoft.Extensions.Options;

namespace Api.Services;

public class PhotoStorageOptions
{
    public const string Section = "Storage";

    /// <summary>Folder for the photo files. Relative paths are resolved against the app's content root.</summary>
    public string PhotosPath { get; set; } = "photos";
}

public interface IPhotoStorage
{
    Task SaveAsync(int assetId, string storedName, Stream content, CancellationToken ct);
    Stream? OpenRead(int assetId, string storedName);
    void Delete(int assetId, string storedName);
    void DeleteAll(int assetId);
}

/// <summary>Photos on disk: {PhotosPath}/{assetId}/{storedName}.</summary>
public class PhotoStorage(IOptions<PhotoStorageOptions> options, IHostEnvironment env) : IPhotoStorage
{
    private string Root => Path.GetFullPath(options.Value.PhotosPath, env.ContentRootPath);

    public async Task SaveAsync(int assetId, string storedName, Stream content, CancellationToken ct)
    {
        Directory.CreateDirectory(Dir(assetId));
        await using var file = File.Create(PathOf(assetId, storedName));
        await content.CopyToAsync(file, ct);
    }

    public Stream? OpenRead(int assetId, string storedName)
    {
        var path = PathOf(assetId, storedName);
        return File.Exists(path) ? File.OpenRead(path) : null;
    }

    public void Delete(int assetId, string storedName)
    {
        var path = PathOf(assetId, storedName);
        if (File.Exists(path)) File.Delete(path);
    }

    public void DeleteAll(int assetId)
    {
        var dir = Dir(assetId);
        if (Directory.Exists(dir)) Directory.Delete(dir, recursive: true);
    }

    private string Dir(int assetId) => Path.Combine(Root, assetId.ToString());

    // Names are generated by the service, but never trust them as paths anyway.
    private string PathOf(int assetId, string storedName) => Path.Combine(Dir(assetId), Path.GetFileName(storedName));
}
